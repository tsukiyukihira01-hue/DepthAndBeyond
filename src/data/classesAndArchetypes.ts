// Helper Functions - Modular Lookups
export function getClassDefinition(id?: string): CharacterClassDefinition {
  if (!id) return CHARACTER_CLASSES[0];
  const normalized = id.toLowerCase().trim();

  // Exact ID or Name match
  const match = CHARACTER_CLASSES.find(
    (c) => c.id === id || c.name.toLowerCase() === normalized || c.id === normalized
  );
  if (match) return match;

  // Legacy/Alias mapping
  if (normalized.includes('vanguard') || normalized.includes('crusader')) {
    return CHARACTER_CLASSES.find((c) => c.id === 'sentinel') || CHARACTER_CLASSES[0];
  }
  if (normalized.includes('elementalist') || normalized.includes('high_elementalist')) {
    return CHARACTER_CLASSES.find((c) => c.id === 'mage') || CHARACTER_CLASSES[0];
  }
  if (normalized.includes('assassin') || normalized.includes('shadow')) {
    return CHARACTER_CLASSES.find((c) => c.id === 'rogue') || CHARACTER_CLASSES[0];
  }
  if (normalized.includes('holy_sentinel') || normalized.includes('cleric')) {
    return CHARACTER_CLASSES.find((c) => c.id === 'paladin') || CHARACTER_CLASSES[0];
  }
  if (normalized.includes('marksman') || normalized.includes('celestial') || normalized.includes('archer')) {
    return CHARACTER_CLASSES.find((c) => c.id === 'ranger') || CHARACTER_CLASSES[0];
  }
  if (normalized.includes('warden') || normalized.includes('rift')) {
    return CHARACTER_CLASSES.find((c) => c.id === 'sorcerer') || CHARACTER_CLASSES[0];
  }

  return CHARACTER_CLASSES[0];
}

export function getArchetypeDefinition(id?: string): ArchetypeDefinition {
  return (
    ARCHETYPES.find((a) => a.id === id) ||
    ARCHETYPES.find((a) => a.name.toLowerCase() === id?.toLowerCase()) ||
    ARCHETYPES[0]
  );
}

// Compute starting stats modularly
export function calculateStartingStats(classId?: string, archetypeId?: string): CharacterStats {
  const cls = getClassDefinition(classId);
  const arch = getArchetypeDefinition(archetypeId);

  const baseHp = 100 + cls.baseStatsBonus.hp + (arch.statBonus.hp || 0);
  const baseMana = 50 + cls.baseStatsBonus.mana + (arch.statBonus.mana || 0);

  return {
    hp: Math.max(50, baseHp),
    maxHp: Math.max(50, baseHp),
    mana: Math.max(20, baseMana),
    maxMana: Math.max(20, baseMana),
    ward: 0,
    maxWard: 0,
    str: Math.max(1, 5 + cls.baseStatsBonus.str + (arch.statBonus.str || 0)),
    def: Math.max(1, 4 + cls.baseStatsBonus.def + (arch.statBonus.def || 0)),
    int: Math.max(1, 5 + cls.baseStatsBonus.int + (arch.statBonus.int || 0)),
    wis: Math.max(1, 4 + cls.baseStatsBonus.wis + (arch.statBonus.wis || 0)),
    spd: Math.max(1, 5 + cls.baseStatsBonus.spd + (arch.statBonus.spd || 0)),
    dex: Math.max(1, 5 + cls.baseStatsBonus.dex + (arch.statBonus.dex || 0)),
    unassignedPoints: 0,
  };
}
